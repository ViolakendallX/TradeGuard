  const res = decide();
  const { trade } = res.record;
  assert.equal(trade.asset, 'RNVDA');
  assert.equal(trade.direction, 'bullish');
  assert.equal(trade.thesis, CONTEXT.thesis);
  assert.equal(trade.timeframe, 'swing');
