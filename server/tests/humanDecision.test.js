/**
 * Human decision service tests (Phase 9).
 *
 * The service RECORDS the trader's decision. These tests exist mostly to prove
 * the things it must never do: choose, suggest, score, generate a reason,
 * invent a default, recalculate risk, or execute anything.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  runHumanDecision,
  validateDecision,
  buildDecisionRecord,
  pendingDecision,
  cleanDecisionContext,
  DECISION_STATUS,
  DECISION_STATUS_LABELS,
  DECISIONS,
  DECISION_HINTS,
  DECISION_OWNERSHIP_NOTICE,
  DECISION_METHOD_NOTE,
  DECISION_DISCLAIMER,
  DECISION_LIMITATIONS,
  RECORDED_PREFIX,
  REASON_MIN_LENGTH,
  REASON_MAX_LENGTH,
} from '../services/humanDecision.js';
import { runRiskAssessment } from '../services/riskEngine.js';

// --- fixtures ---------------------------------------------------------------

/** The exact manual-test trade: bullish rNVDA 100/95/50 -> 5 / 10 / 50. */
const CONTEXT = {
  asset: 'rNVDA',
  direction: 'bullish',
  thesis:
    'I think rNVDA will continue higher over the next few days because the current momentum is bullish and the price may continue to push higher if it holds above the key support area.',
  timeframe: 'swing',
  entryPrice: 100,
  invalidationPrice: 95,
  riskAmount: 50,
  confidence: 7,
  existingPosition: 'none',
};

/** The Phase 6 result for that trade, produced by the real engine. */
const RISK = runRiskAssessment(CONTEXT);

/** A reason the trader might genuinely write. Never generated by TradeGuard. */
const REAL_REASON =
  'Price held the support area on the last two sessions and momentum is still pointing up, so I am comfortable risking 50 on this setup.';

const FIXED_TIME = new Date('2026-09-19T20:00:00.000Z');

/** Convenience: run the service with a fixed clock. */
const decide = (over = {}) =>
  runHumanDecision({ decision: 'TAKE', reason: REAL_REASON, context: CONTEXT, risk: RISK, ...over }, FIXED_TIME);

const blobOf = (value) => JSON.stringify(value).toLowerCase();

// --- 1-3. the three options save --------------------------------------------

test('TAKE with a valid reason is recorded', () => {
  const res = decide({ decision: 'TAKE' });
  assert.equal(res.ok, true);
  assert.deepEqual(res.errors, {});
  assert.equal(res.record.status, DECISION_STATUS.RECORDED);
  assert.equal(res.record.statusLabel, 'DECISION RECORDED');
  assert.equal(res.record.decision, 'TAKE');
  assert.equal(res.record.reason, REAL_REASON);
});

test('WAIT with a valid reason is recorded', () => {
  const res = decide({ decision: 'WAIT' });
  assert.equal(res.ok, true);
  assert.equal(res.record.status, DECISION_STATUS.RECORDED);
  assert.equal(res.record.decision, 'WAIT');
  assert.equal(res.record.reason, REAL_REASON);
});

test('SKIP with a valid reason is recorded', () => {
  const res = decide({ decision: 'SKIP' });
  assert.equal(res.ok, true);
  assert.equal(res.record.status, DECISION_STATUS.RECORDED);
  assert.equal(res.record.decision, 'SKIP');
  assert.equal(res.record.reason, REAL_REASON);
});

test('every option in the vocabulary is recordable, and there are exactly three', () => {
  assert.deepEqual([...DECISIONS], ['TAKE', 'WAIT', 'SKIP']);
  for (const decision of DECISIONS) {
    const res = decide({ decision });
    assert.equal(res.ok, true, `${decision} should be recordable`);
    assert.equal(res.record.decision, decision);
    assert.ok(DECISION_HINTS[decision], `${decision} should have a hint`);
  }
});

test('the decision is recorded case-insensitively but stored canonically', () => {
  for (const raw of ['take', 'Take', '  take  ', 'TAKE']) {
    const res = decide({ decision: raw });
    assert.equal(res.ok, true, `${raw} should be accepted`);
    assert.equal(res.record.decision, 'TAKE', `${raw} should normalise to TAKE`);
  }
});

// --- 4. missing decision ----------------------------------------------------

test('a missing decision is rejected, never defaulted', () => {
  for (const decision of [undefined, null, '', '   ']) {
    const res = decide({ decision });
    assert.equal(res.ok, false, `${JSON.stringify(decision)} must not be accepted`);
    assert.ok(res.errors.decision, 'the decision error should be reported');
    assert.equal(res.record.decision, null, 'no decision may be invented');
    assert.equal(res.record.status, DECISION_STATUS.REQUIRED);
  }
});

test('the pending record is DECISION REQUIRED and is not a placeholder choice', () => {
  const pending = pendingDecision();
  assert.equal(pending.status, DECISION_STATUS.REQUIRED);
  assert.equal(pending.statusLabel, 'DECISION REQUIRED');
  assert.equal(pending.decision, null);
  assert.equal(pending.reason, null);
  assert.equal(pending.timestamp, null);
  assert.equal(pending.recordedPrefix, RECORDED_PREFIX);
  assert.equal(pending.executed, false);
  // The honest incomplete state still carries the guarantees.
  assert.equal(pending.ownershipNotice, DECISION_OWNERSHIP_NOTICE);
  assert.equal(pending.disclaimer, DECISION_DISCLAIMER);
  assert.deepEqual(pending.limitations, [...DECISION_LIMITATIONS]);
});

// --- 5-6. empty / whitespace-only reason ------------------------------------

test('an empty reason is rejected', () => {
  for (const reason of [undefined, null, '']) {
    const res = decide({ reason });
    assert.equal(res.ok, false, 'an empty reason must be rejected');
    assert.ok(res.errors.reason);
    assert.equal(res.record.reason, null, 'no reason may be invented');
  }
});

test('a whitespace-only reason is rejected', () => {
  for (const reason of [' ', '   ', '\t', '\n', ' \t \n ']) {
    const res = decide({ reason });
    assert.equal(res.ok, false, `${JSON.stringify(reason)} must be rejected`);
    assert.ok(res.errors.reason);
    assert.equal(res.record.reason, null);
  }
});

test('the reason is trimmed before it is stored or validated', () => {
  const res = decide({ reason: `   ${REAL_REASON}   ` });
  assert.equal(res.ok, true);
  assert.equal(res.record.reason, REAL_REASON, 'surrounding whitespace should be trimmed');

  // A reason that is only just long enough AFTER trimming must pass; the same
  // string padded with whitespace must not pass on the strength of the padding.
  const short = 'okay';
  const padded = `   ${short}   `;
  assert.equal(decide({ reason: short }).ok, true);
  assert.equal(decide({ reason: padded }).ok, true);
  assert.equal(decide({ reason: padded }).record.reason, short);
});

test('a too-short reason is rejected and a too-long reason is rejected', () => {
  const tooShort = 'a'.repeat(REASON_MIN_LENGTH - 1);
  const shortRes = decide({ reason: tooShort });
  assert.equal(shortRes.ok, false);
  assert.ok(shortRes.errors.reason);

  const tooLong = 'a'.repeat(REASON_MAX_LENGTH + 1);
  const longRes = decide({ reason: tooLong });
  assert.equal(longRes.ok, false);
  assert.ok(longRes.errors.reason);

  // The bounds themselves are inclusive.
  assert.equal(decide({ reason: 'a'.repeat(REASON_MIN_LENGTH) }).ok, true);
  assert.equal(decide({ reason: 'a'.repeat(REASON_MAX_LENGTH) }).ok, true);
});

// --- 7. unsupported decision value ------------------------------------------

test('an unsupported decision value is rejected', () => {
  const bad = ['BUY', 'SELL', 'PASS', 'HOLD', 'MAYBE', 'YES', 'NO', 'takee', '0', '1', 'true', '{}'];
  for (const decision of bad) {
    const res = decide({ decision });
    assert.equal(res.ok, false, `${decision} must be rejected`);
    assert.ok(res.errors.decision, `${decision} should report a decision error`);
    assert.equal(res.record.decision, null, `${decision} must not be stored`);
    assert.equal(res.record.status, DECISION_STATUS.REQUIRED);
  }
});

test('BUY / SELL / PASS are specifically not part of the vocabulary', () => {
  // These are instructions, not records of a human choice. The phase vocabulary
  // is deliberately TAKE / WAIT / SKIP and must not drift towards them.
  for (const forbidden of ['BUY', 'SELL', 'PASS']) {
    assert.equal(DECISIONS.includes(forbidden), false, `${forbidden} must not be an option`);
    assert.equal(decide({ decision: forbidden }).ok, false);
  }
});

test('a malformed request body is rejected rather than throwing', () => {
  for (const payload of [null, undefined, 'TAKE', 42, [], { decision: {} }, { decision: [] }]) {
    const res = runHumanDecision(payload, FIXED_TIME);
    assert.equal(res.ok, false, `${JSON.stringify(payload)} must be rejected`);
    assert.ok(res.errors.decision || res.errors.asset);
  }
});

test('a malformed trade context is rejected', () => {
  const res = decide({ context: { ...CONTEXT, entryPrice: 'abc' } });
  assert.equal(res.ok, false);
  assert.ok(res.errors.entryPrice);

  const nan = decide({ context: { ...CONTEXT, riskAmount: 'nope' } });
  assert.equal(nan.ok, false);
  assert.ok(nan.errors.riskAmount);

  const neg = decide({ context: { ...CONTEXT, invalidationPrice: '-5' } });
  assert.equal(neg.ok, false);
  assert.ok(neg.errors.invalidationPrice);

  const conf = decide({ context: { ...CONTEXT, confidence: 99 } });
  assert.equal(conf.ok, false);
  assert.ok(conf.errors.confidence);
});

test('a decision with no trade context at all is rejected', () => {
  const res = runHumanDecision({ decision: 'TAKE', reason: REAL_REASON, context: {} }, FIXED_TIME);
  assert.equal(res.ok, false);
  assert.ok(res.errors.asset);
  assert.equal(res.record.decision, null);
});

test('multiple problems are reported together, not one at a time', () => {
  const res = runHumanDecision({ decision: 'MAYBE', reason: '   ', context: {} }, FIXED_TIME);
  assert.equal(res.ok, false);
  assert.ok(res.errors.decision);
  assert.ok(res.errors.reason);
  assert.ok(res.errors.asset);
});

