// --- the record belongs to the trader, not to TradeGuard -------------------

test('the record attributes the decision to the trader', () => {
  const res = decide();
  assert.equal(res.record.ownership, 'The decision was recorded by the trader.');
  assert.equal(res.record.recordedPrefix, 'You recorded:');
  assert.match(res.record.reasonSource, /not generated by TradeGuard/i);
  assert.equal(res.record.ownershipNotice, DECISION_OWNERSHIP_NOTICE);
});

test('the ownership notice says TradeGuard does not choose', () => {
  assert.match(DECISION_OWNERSHIP_NOTICE, /does not choose this for you/i);
  assert.match(DECISION_OWNERSHIP_NOTICE, /Record the decision you are making/i);
});

test('the record never claims TradeGuard recommends, suggests or scores', () => {
  for (const decision of DECISIONS) {
    const res = decide({ decision });
    const blob = blobOf(res.record);

    for (const forbidden of [
      'tradeguard recommends',
      'we recommend',
      'we suggest',
      'you should',
      'recommended action',
      'trade score',
      'score:',
      'confidence score',
      'ranking',
      'ranked',
    ]) {
      assert.ok(!blob.includes(forbidden), `"${forbidden}" must not appear for ${decision}`);
    }
  }
});

test('the record never expresses a verdict or a prediction', () => {
  // The service legitimately NAMES these things while denying them — "does not
  // tell you whether this is a good or bad trade", "not a prediction". Those
  // are the honest sentences we want. What must never appear is an ASSERTION of
  // a verdict, so each match is checked for a negation immediately before it.
  const NEGATORS = [
    'not ', "not'", "n't ", 'no ', 'never ', 'nor ', 'neither ', 'without ', 'does not', 'do not',
    'is not', 'are not', 'was not', 'cannot', 'rather than', 'instead of', 'neither',
  ];
  const NEGATION_WINDOW = 90;

  const blob = blobOf(decide().record);
  for (const forbidden of [
    /\bbuy\b/,
    /\bsell\b/,
    /\bpass\b/,
    'good trade',
    'bad trade',
    'safe trade',
    'worth taking',
    'likely to work',
    'probability',
    'win rate',
    'expected return',
    'guaranteed',
    'prediction',
    'will rise',
    'will fall',
  ]) {
    const re = forbidden instanceof RegExp
      ? new RegExp(forbidden.source, 'gi')
      : new RegExp(forbidden.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi');

    let match;
    while ((match = re.exec(blob)) !== null) {
      const before = blob.slice(Math.max(0, match.index - NEGATION_WINDOW), match.index);
      const negated = NEGATORS.some((negator) => before.includes(negator));
      assert.ok(
        negated,
        `"${forbidden}" is asserted as a verdict — the service must only ever deny it. Context: …${blob.slice(
          Math.max(0, match.index - 70),
          match.index + 70
        )}…`
      );
      if (match[0].length === 0) re.lastIndex += 1; // guard against zero-width loops
    }
  }
});

test('the reason is stored verbatim and never rewritten', () => {
  // Includes the trader's own words, punctuation and casing — none of it touched.
  const reason = 'I am NOT taking this: rNVDA looks extended here, and I want to see it hold 95 first!!';
  const res = decide({ reason });
  assert.equal(res.record.reason, reason);
  assert.equal(res.record.reason.length, reason.length);
});

test('the reason cannot be swapped for the thesis or any other text', () => {
  // A defensive check that the service is not quietly substituting another field
  // when the reason is missing.
  const res = decide({ reason: '' });
  assert.equal(res.ok, false);
  assert.equal(res.record.reason, null);
  assert.notEqual(res.record.reason, CONTEXT.thesis);
});

test('nothing is executed and the record says so', () => {
  const res = decide();
  assert.equal(res.record.executed, false);
  assert.match(res.record.executionNotice, /Nothing has been executed/i);
  assert.match(res.record.executionNotice, /No order was placed/i);
});

test('the method note and disclaimer state the boundary', () => {
  const res = decide();
  assert.equal(res.record.methodNote, DECISION_METHOD_NOTE);
  assert.equal(res.record.disclaimer, DECISION_DISCLAIMER);
  assert.match(DECISION_METHOD_NOTE, /does not make the decision/i);
  assert.match(DECISION_DISCLAIMER, /not a trading instruction/i);
});

test('the standing limitations are always attached', () => {
  const res = decide();
  assert.deepEqual(res.record.limitations, [...DECISION_LIMITATIONS]);
  assert.ok(res.record.limitations.length >= 4);
  assert.ok(res.record.limitations.some((l) => /not a successful trade/i.test(l)));
  assert.ok(res.record.limitations.some((l) => /Nothing has been executed/i.test(l)));
});

// --- determinism and purity -------------------------------------------------

test('the service is deterministic for the same input and clock', () => {
  const a = decide({ decision: 'WAIT' });
  const b = decide({ decision: 'WAIT' });
  assert.deepEqual(a, b);
});

test('validation is pure and does not mutate its input', () => {
  const payload = { decision: 'take', reason: `  ${REAL_REASON}  `, context: { ...CONTEXT }, risk: RISK };
  const snapshot = JSON.parse(JSON.stringify(payload));
  validateDecision(payload);
  buildDecisionRecord(
    { decision: 'TAKE', reason: REAL_REASON, context: CONTEXT, riskContext: { state: 'available' } },
    FIXED_TIME
  );
  assert.deepEqual(payload, snapshot);
});

test('the service imports no provider and makes no network call', async () => {
  const src = await import('node:fs/promises').then((fs) =>
    fs.readFile(new URL('../services/humanDecision.js', import.meta.url), 'utf8')
  );
  // Strip the doc comment, which legitimately DISCUSSES what the module does not do.
  const code = src.replace(/\/\*\*[\s\S]*?\*\//g, '');
  for (const forbidden of ['fetch(', 'http://', 'https://', 'node-fetch', 'axios', 'process.env']) {
    assert.ok(!code.includes(forbidden), `humanDecision.js must not contain ${forbidden}`);
  }
});

// --- state vocabulary -------------------------------------------------------

test('there are exactly two deterministic decision states', () => {
  assert.deepEqual(Object.keys(DECISION_STATUS).sort(), ['RECORDED', 'REQUIRED']);
  assert.equal(DECISION_STATUS.REQUIRED, 'required');
  assert.equal(DECISION_STATUS.RECORDED, 'recorded');
  assert.deepEqual(Object.keys(DECISION_STATUS_LABELS).sort(), ['recorded', 'required']);
  assert.equal(DECISION_STATUS_LABELS.required, 'DECISION REQUIRED');
  assert.equal(DECISION_STATUS_LABELS.recorded, 'DECISION RECORDED');
});

test('there is no confidence, quality or recommendation score anywhere', () => {
  const res = decide();
  const keys = Object.keys(res.record).map((k) => k.toLowerCase());
  for (const forbidden of ['score', 'rating', 'recommendation', 'conviction', 'grade', 'probability', 'confidence']) {
    assert.ok(!keys.includes(forbidden), `the record must not carry a ${forbidden} field`);
  }
});
